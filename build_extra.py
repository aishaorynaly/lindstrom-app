"""Generate portal/extra_data.js: asset-level facts the portal's embedded data does not carry.

The portal ships with monthly aggregates only. The hygiene flag (garments with no laundry scan for more than
180 days) needs the asset-level cycle log, so it is computed here with the same engine the tests reconcile to
the workbook, and written as plain data.

    python build_extra.py
"""
import json
from pathlib import Path

import config
import engine
import loader
from engine import Scope

OUT = Path(__file__).parent / "portal" / "extra_data.js"


def build() -> dict:
    full = loader.load_workbook()
    sites: dict[str, dict] = {}
    for customer in full.customers["customer_id"]:
        ds = loader.for_customer(full, customer)
        assets = engine.hygiene_assets(ds, Scope(customer))
        latest = ds.activity[ds.activity["month"] == ds.months[-1]]
        allocated = latest[latest["product_group"].isin(config.HYGIENE_GROUPS)].groupby("site_id")["allocated_pieces"].sum()
        flagged = assets.assign(flag=assets["days_since_scan"] > config.HYGIENE_DAYS).groupby("site_id")
        for site_id in ds.sites["site_id"]:
            if site_id in allocated.index or site_id in flagged.groups:
                sites[site_id] = {
                    "traced": int(flagged.size().get(site_id, 0)),
                    "flagged": int(flagged["flag"].sum().get(site_id, 0)),
                    "allocated": int(allocated.get(site_id, 0)),
                }
    return {
        "asOf": str(full.as_of.date()),
        "days": config.HYGIENE_DAYS,
        "groups": list(config.HYGIENE_GROUPS),
        "sites": sites,
        "note": "Generated by build_extra.py from the Service_Cycles sheet. Hygiene-critical garments only.",
    }


if __name__ == "__main__":
    data = build()
    OUT.write_text("/* generated by build_extra.py, do not edit */\nconst EXTRA = " + json.dumps(data, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    flagged = sum(v["flagged"] for v in data["sites"].values())
    traced = sum(v["traced"] for v in data["sites"].values())
    print(f"wrote {OUT} | sites {len(data['sites'])} | traced {traced} | flagged {flagged} | as of {data['asOf']}")
